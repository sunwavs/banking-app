-- =============================================================================
-- RIS database schema
--
-- Creates the extension, types, tables, the transfer trigger and the report
-- procedures. The script runs in a single transaction and never drops anything:
-- if any object already exists it fails and rolls back. To start over:
--     dropdb Bank && createdb Bank
--
-- Usage:
--     createdb Bank
--     psql -v ON_ERROR_STOP=1 -d Bank -f db/schema.sql -f db/seed.sql
--
-- Conventions
--   * Money is numeric(18,2) (domain money_amount): no floating-point rounding errors.
--   * Account numbers are 8-12 digits (domain account_number); every column that holds
--     an account number uses this domain, so the type can never diverge.
--   * Timestamps are timestamptz. Calendar months used by reports and by the
--     application are months in the session time zone (the application sets UTC).
--   * Error codes raised by the database for the application:
--       RIS02  insufficient funds on the sender account
--       RIS03  an attempt to change or delete a remittance
-- =============================================================================

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;   -- trusted extension since PostgreSQL 13

-- ---------------------------------------------------------------------------
-- Types
-- ---------------------------------------------------------------------------

CREATE DOMAIN account_number AS varchar(12)
    CHECK (VALUE ~ '^[0-9]{8,12}$');

CREATE DOMAIN money_amount AS numeric(18, 2);

-- The roles must match the keys of app/access.json.
CREATE TYPE user_role AS ENUM ('external', 'manager', 'analyst', 'operator');

-- ---------------------------------------------------------------------------
-- Passwords
-- ---------------------------------------------------------------------------

-- Returns a bcrypt hash of a plaintext password. Use it whenever a user is created
-- directly in SQL:  INSERT INTO users (...) VALUES (..., hash_password('secret'), ...)
CREATE FUNCTION hash_password(plain text) RETURNS text
    LANGUAGE sql
AS $$
    SELECT crypt(plain, gen_salt('bf', 12));
$$;

-- ---------------------------------------------------------------------------
-- Clients, accounts and users
-- ---------------------------------------------------------------------------

CREATE TABLE clients (
    contract_num varchar(20)  PRIMARY KEY,
    last_name    varchar(60)  NOT NULL,
    address      varchar(120),
    birthday     date,
    phone_num    varchar(20)  NOT NULL,
    reg_date     date         NOT NULL,
    term_date    date,                       -- contract termination date; NULL while active
    CHECK (term_date IS NULL OR term_date >= reg_date)
);

CREATE TABLE accounts (
    account_num  account_number PRIMARY KEY,
    balance      money_amount   NOT NULL CHECK (balance >= 0),
    last_change  timestamptz    NOT NULL DEFAULT now(),
    contract_num varchar(20)    NOT NULL REFERENCES clients (contract_num)
);

CREATE INDEX accounts_contract_num_idx ON accounts (contract_num);

-- Everyone who signs in to the web application: bank clients (role 'external', linked to
-- their contract) and bank staff (any other role, no contract).
CREATE TABLE users (
    id            integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login         varchar(64) NOT NULL UNIQUE CHECK (login <> '' AND login = btrim(login)),
    -- Only bcrypt hashes can be stored: a plaintext password is rejected by this constraint.
    password_hash text        NOT NULL
                  CHECK (password_hash ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$'),
    role          user_role   NOT NULL,
    contract_num  varchar(20) REFERENCES clients (contract_num),
    -- A deactivated user cannot sign in, and the sessions that are already open stop working.
    is_active     boolean     NOT NULL DEFAULT true,
    CONSTRAINT users_role_contract_check CHECK ((role = 'external') = (contract_num IS NOT NULL))
);

-- ---------------------------------------------------------------------------
-- Remittances
-- ---------------------------------------------------------------------------

CREATE TABLE remittances (
    rem_id              integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount              money_amount  NOT NULL CHECK (amount > 0),
    remittance_moment   timestamptz   NOT NULL DEFAULT now(),
    sender_account_id   account_number NOT NULL
                        CONSTRAINT remittances_sender_fkey
                        REFERENCES accounts (account_num) ON UPDATE RESTRICT ON DELETE RESTRICT,
    receiver_account_id account_number NOT NULL
                        CONSTRAINT remittances_receiver_fkey
                        REFERENCES accounts (account_num) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT remittances_distinct_accounts_check CHECK (sender_account_id <> receiver_account_id)
);

CREATE INDEX remittances_moment_idx   ON remittances (remittance_moment);
CREATE INDEX remittances_sender_idx   ON remittances (sender_account_id, remittance_moment);
CREATE INDEX remittances_receiver_idx ON remittances (receiver_account_id, remittance_moment);

-- A remittance is processed by two triggers.
--
-- 1. lock_remittance_accounts (BEFORE INSERT) locks both accounts, in a fixed order (by account
--    number), before anything else touches them. Concurrent remittances on the same account are
--    serialized, and opposite remittances (A -> B and B -> A) cannot deadlock. The lock must be
--    taken BEFORE the insert: the foreign keys of remittances take shared row locks (FOR KEY
--    SHARE) on both accounts in AFTER triggers, and two transactions that each hold a shared lock
--    and then try to upgrade it to FOR UPDATE would wait for each other.
-- 2. apply_remittance (AFTER INSERT) verifies the balance and moves the money. Side effects
--    happen only once the row has really been inserted.
--
-- Either trigger aborts the INSERT by raising an error. The existence of both accounts is
-- guaranteed by the foreign keys; CHECK (balance >= 0) on accounts is a second line of defense.

-- A remittance is a ledger entry: it is never changed or deleted afterwards (the balances
-- would no longer match the history). A mistake is corrected by a compensating remittance.
CREATE FUNCTION forbid_remittance_change() RETURNS trigger
    LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'Remittances cannot be changed or deleted'
        USING ERRCODE = 'RIS03';
END
$$;

CREATE TRIGGER remittances_append_only
    BEFORE UPDATE OR DELETE ON remittances
    FOR EACH ROW EXECUTE FUNCTION forbid_remittance_change();

CREATE FUNCTION lock_remittance_accounts() RETURNS trigger
    LANGUAGE plpgsql
AS $$
BEGIN
    PERFORM 1
    FROM accounts
    WHERE account_num IN (NEW.sender_account_id, NEW.receiver_account_id)
    ORDER BY account_num
    FOR UPDATE;

    RETURN NEW;
END
$$;

CREATE FUNCTION apply_remittance() RETURNS trigger
    LANGUAGE plpgsql
AS $$
DECLARE
    sender_balance money_amount;
BEGIN
    SELECT balance INTO sender_balance
    FROM accounts
    WHERE account_num = NEW.sender_account_id;

    IF sender_balance < NEW.amount THEN
        RAISE EXCEPTION 'Insufficient funds on account %', NEW.sender_account_id
            USING ERRCODE = 'RIS02';
    END IF;

    UPDATE accounts
    SET balance = balance - NEW.amount,
        last_change = greatest(last_change, NEW.remittance_moment)
    WHERE account_num = NEW.sender_account_id;

    UPDATE accounts
    SET balance = balance + NEW.amount,
        last_change = greatest(last_change, NEW.remittance_moment)
    WHERE account_num = NEW.receiver_account_id;

    RETURN NEW;
END
$$;

CREATE TRIGGER on_transfer_lock
    BEFORE INSERT ON remittances
    FOR EACH ROW EXECUTE FUNCTION lock_remittance_accounts();

CREATE TRIGGER on_transfer
    AFTER INSERT ON remittances
    FOR EACH ROW EXECUTE FUNCTION apply_remittance();

-- ---------------------------------------------------------------------------
-- Investment catalog and orders
-- ---------------------------------------------------------------------------

CREATE TABLE products (
    prod_id      bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prod_name    varchar(100) NOT NULL UNIQUE,
    prod_price   money_amount NOT NULL CHECK (prod_price >= 0),
    prod_balance bigint       NOT NULL CHECK (prod_balance >= 0)   -- units in stock
);

CREATE TABLE orders (
    order_id            bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             integer     NOT NULL REFERENCES users (id),
    order_creation_time timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX orders_user_id_idx ON orders (user_id);

CREATE TABLE order_details (
    rec_id     bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   bigint       NOT NULL REFERENCES orders (order_id),
    prod_id    bigint       NOT NULL REFERENCES products (prod_id),
    count_item integer      NOT NULL CHECK (count_item > 0),
    line_total money_amount NOT NULL CHECK (line_total >= 0),   -- unit price * count_item
    UNIQUE (order_id, prod_id)
);

CREATE INDEX order_details_prod_id_idx ON order_details (prod_id);

-- ---------------------------------------------------------------------------
-- Monthly reports
--
-- One row per account and month. report_date is always the first day of the month.
-- ---------------------------------------------------------------------------

CREATE TABLE sent_report (
    record_id   bigint         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_date date           NOT NULL CHECK (extract(day FROM report_date) = 1),
    account_num account_number NOT NULL REFERENCES accounts (account_num),
    sent_sum    money_amount   NOT NULL,
    UNIQUE (report_date, account_num)
);

CREATE TABLE transfer_count_report (
    record_id      bigint         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_date    date           NOT NULL CHECK (extract(day FROM report_date) = 1),
    account_num    account_number NOT NULL REFERENCES accounts (account_num),
    transfer_count bigint         NOT NULL CHECK (transfer_count > 0),
    UNIQUE (report_date, account_num)
);

-- Stores, for every sender, the total amount sent during the month of report_date_arg.
-- Idempotent: rows that already exist are left untouched, so concurrent or repeated calls
-- never produce duplicates.
CREATE PROCEDURE create_sent_report(report_date_arg date)
    LANGUAGE sql
AS $$
    WITH period AS (
        SELECT date_trunc('month', report_date_arg::timestamp) AS month_start
    )
    INSERT INTO sent_report (report_date, account_num, sent_sum)
    SELECT p.month_start::date, r.sender_account_id, sum(r.amount)
    FROM period p
    JOIN remittances r
      ON r.remittance_moment >= p.month_start
     AND r.remittance_moment <  p.month_start + interval '1 month'
    GROUP BY p.month_start, r.sender_account_id
    ON CONFLICT (report_date, account_num) DO NOTHING;
$$;

-- Stores, for every sender, the number of remittances made during the month of
-- report_date_arg. Idempotent, like create_sent_report.
CREATE PROCEDURE create_transfer_count_report(report_date_arg date)
    LANGUAGE sql
AS $$
    WITH period AS (
        SELECT date_trunc('month', report_date_arg::timestamp) AS month_start
    )
    INSERT INTO transfer_count_report (report_date, account_num, transfer_count)
    SELECT p.month_start::date, r.sender_account_id, count(*)
    FROM period p
    JOIN remittances r
      ON r.remittance_moment >= p.month_start
     AND r.remittance_moment <  p.month_start + interval '1 month'
    GROUP BY p.month_start, r.sender_account_id
    ON CONFLICT (report_date, account_num) DO NOTHING;
$$;

-- ---------------------------------------------------------------------------
-- Documentation visible in psql (\d+) and in database clients
-- ---------------------------------------------------------------------------

COMMENT ON TABLE clients               IS 'Bank clients, identified by their contract number.';
COMMENT ON TABLE accounts              IS 'Accounts of the clients. Balances are changed only by the on_transfer trigger.';
COMMENT ON TABLE users                 IS 'Everyone who signs in to the web application: bank clients (role external) and staff.';
COMMENT ON TABLE remittances           IS 'Append-only ledger of money transfers between accounts.';
COMMENT ON TABLE products              IS 'Investment catalog with the units in stock.';
COMMENT ON TABLE orders                IS 'Orders placed by users.';
COMMENT ON TABLE order_details         IS 'Lines of an order: one row per product.';
COMMENT ON TABLE sent_report           IS 'Monthly report: the amount sent from every account.';
COMMENT ON TABLE transfer_count_report IS 'Monthly report: the number of remittances made from every account.';

COMMENT ON COLUMN users.password_hash        IS 'bcrypt hash; plaintext passwords are rejected by a CHECK constraint.';
COMMENT ON COLUMN users.is_active            IS 'False for a deactivated user: no sign-in, open sessions stop working.';
COMMENT ON COLUMN remittances.amount         IS 'Amount debited from the sender and credited to the receiver (same currency).';
COMMENT ON COLUMN order_details.line_total   IS 'Unit price multiplied by count_item, at the moment of the order.';
COMMENT ON COLUMN products.prod_balance      IS 'Units in stock; decreased by the application when an order is placed.';
COMMENT ON COLUMN sent_report.report_date    IS 'First day of the reported month.';
COMMENT ON COLUMN transfer_count_report.report_date IS 'First day of the reported month.';

COMMIT;
